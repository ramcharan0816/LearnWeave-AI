import os
import logging
from app.password_reset_model import PasswordResetOTP

from fastapi import FastAPI, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from sqlalchemy import text
from sqlalchemy.exc import OperationalError

from app.database import Base, engine
from app import models
from app.routers import quiz, documents, retrieval, rag, auth, password_reset

app = FastAPI(
    title="LearnWeave AI",
    description=(
        "An adaptive AI-powered learning platform "
        "with document upload, semantic search, "
        "and RAG-based answer generation."
    ),
    version="1.0.0",
)
logger = logging.getLogger("uvicorn.error.learnweave")


@app.on_event("startup")
def create_database_tables():
    logger.info("Registered tables: %s", list(Base.metadata.tables.keys()))
    try:
        Base.metadata.create_all(bind=engine)
    except OperationalError:
        # Keep the HTTP service alive so Render can bind its port and expose
        # diagnostics while the database URL or database availability is fixed.
        logger.exception(
            "Database initialization failed. Verify DATABASE_URL uses the "
            "database's internal URL and that both Render services share a region."
        )
        return
    logger.info("Database tables created or verified.")

# CORS configuration. Extra origins (for example a Vercel preview URL)
# can be added with a comma-separated CORS_ALLOW_ORIGINS variable.
ALLOWED_ORIGINS = [
    "http://localhost:3000",
    "http://127.0.0.1:3000",
    "https://learn-weave-ai.vercel.app",
] + [
    origin.strip().rstrip("/")
    for origin in os.getenv("CORS_ALLOW_ORIGINS", "").split(",")
    if origin.strip()
]

# Register API routers
app.include_router(documents.router)
app.include_router(retrieval.router)
app.include_router(rag.router)
app.include_router(quiz.router)
app.include_router(auth.router)
app.include_router(password_reset.router)


@app.exception_handler(OperationalError)
async def database_unavailable_handler(request: Request, exc: OperationalError):
    logger.error("Database request failed for %s %s", request.method, request.url.path)
    return JSONResponse(
        status_code=503,
        content={
            "detail": "The database is temporarily unavailable. Please try again shortly."
        },
    )

@app.get("/")
def root():
    return {
        "message": "Welcome to LearnWeave AI API",
        "status": "running",
        "version": "1.0.0",
        "modules": [
            "Document Upload",
            "Semantic Retrieval",
            "RAG Answer Generation"
        ]
    }


@app.get("/health")
def health_check():
    try:
        with engine.connect() as connection:
            connection.execute(text("SELECT 1"))
        database_status = "connected"
    except OperationalError:
        database_status = "unavailable"

    return {
        "status": "healthy" if database_status == "connected" else "degraded",
        "application": "LearnWeave AI",
        "database": database_status,
    }


# Wrap the complete FastAPI app so CORS headers are also attached to responses
# generated by Starlette's outer error handler (including database failures).
app = CORSMiddleware(
    app=app,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)
